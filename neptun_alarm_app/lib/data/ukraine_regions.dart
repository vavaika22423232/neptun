  /// Отримати список назв всіх областей
  static List<String> get oblastNames => 
      allOblasts.map((o) => o['name'] as String).toList();

  /// Отримати райони для конкретної області
  static List<String> getDistrictsForOblast(String oblast) =>
      districtsByOblast[oblast] ?? [];

  /// Перевірити чи область є небезпечною (прифронтовою)
  static bool isOblastDangerous(String oblast) {
    final oblastData = allOblasts.firstWhere(
      (o) => o['name'] == oblast,
      orElse: () => {'danger': false},
    );
    return oblastData['danger'] as bool;
  }

  /// Отримати іконку для області
  static String getOblastIcon(String oblast) {
    final oblastData = allOblasts.firstWhere(
      (o) => o['name'] == oblast,
      orElse: () => {'icon': '📍'},
    );
    return oblastData['icon'] as String;
  }

  /// Знайти область за назвою району
  static String? findOblastByDistrict(String district) {
    for (final entry in districtsByOblast.entries) {
      if (entry.value.contains(district)) {
        return entry.key;
      }
    }
    return null;
  }
