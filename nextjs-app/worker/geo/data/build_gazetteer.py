# Ukrainian declension suffixes for alias generation
UK_SUFFIXES = ['а', 'у', 'і', 'ом', 'ів', 'ам', 'и', 'ою', 'ю', 'е', 'ей']

_APOSTROPHE_RE = re.compile(r"[''ʼ`´’]")


def _compact_name(s: str) -> str:
    return _APOSTROPHE_RE.sub('', s.lower()).strip()


def ensure_places_fts(conn: sqlite3.Connection) -> None:
    """Rebuild FTS5 index for public place search API."""
    conn.execute("DELETE FROM places_fts")
    conn.executemany(
        "INSERT INTO places_fts(rowid, name_uk, name_norm, oblast_uk) VALUES (?,?,?,?)",
        [
            (row[0], row[1], row[2], row[3])
            for row in conn.execute(
                "SELECT id, name, name_lower, oblast FROM places"
            ).fetchall()
        ],
    )


def build_db(db_path: str = DB_PATH):
    """Build the settlements.db from hardcoded data."""
    if os.path.exists(db_path):
        os.remove(db_path)

    conn = sqlite3.connect(db_path)
    conn.executescript(SCHEMA)

    # Insert settlements
    for s in SETTLEMENTS:
        name, oblast, raion, lat, lng, ptype, pop = s
        conn.execute(
            "INSERT INTO places (name, name_lower, oblast, raion, lat, lng, place_type, population) VALUES (?,?,?,?,?,?,?,?)",
            (name, name.lower(), oblast, raion, lat, lng, ptype, pop),
        )

    # Build auto-aliases: declension forms
    rows = conn.execute("SELECT id, name, name_lower FROM places").fetchall()
    for pid, name, name_lower in rows:
        # Add lowercase variants with common suffixes
        for suffix in UK_SUFFIXES:
            if name_lower.endswith('ь'):
                alias = name_lower[:-1] + suffix
            elif name_lower.endswith('а'):
                alias = name_lower[:-1] + suffix
            elif name_lower.endswith('о'):
                alias = name_lower[:-1] + suffix
            elif name_lower.endswith('і'):
                alias = name_lower[:-1] + suffix
            else:
                alias = name_lower + suffix
            if alias != name_lower:
                conn.execute(
                    "INSERT INTO aliases (alias, canonical_id, priority) VALUES (?,?,0)",
                    (alias, pid),
                )

    # Apostrophe-less spellings (Камянське → Кам'янське)
    for pid, name, name_lower in rows:
        compact = _compact_name(name_lower)
        if compact and compact != name_lower:
            conn.execute(
                "INSERT INTO aliases (alias, canonical_id, priority) VALUES (?,?,4)",
                (compact, pid),
            )

    # Add Russian / translit aliases
    for alias_key, canonical_name in ALIAS_MAP.items():
        row = conn.execute(
            "SELECT id FROM places WHERE name = ? LIMIT 1", (canonical_name,)
        ).fetchone()
        if row:
            conn.execute(
                "INSERT INTO aliases (alias, canonical_id, priority) VALUES (?,?,5)",
                (alias_key.lower(), row[0]),
            )

    ensure_places_fts(conn)
    conn.commit()
    count = conn.execute("SELECT COUNT(*) FROM places").fetchone()[0]
    alias_count = conn.execute("SELECT COUNT(*) FROM aliases").fetchone()[0]
    conn.close()
    print(f"Built {db_path}: {count} places, {alias_count} aliases")
    return db_path


def build_from_csv(csv_path: str, db_path: str = DB_PATH):
    """Build settlements.db from a Codifier CSV file."""
    if os.path.exists(db_path):
        os.remove(db_path)

    conn = sqlite3.connect(db_path)
    conn.executescript(SCHEMA)

    count = 0
    with open(csv_path, encoding='utf-8') as f:
        reader = csv.DictReader(f, delimiter=';')
        for row in reader:
            name = row.get('Назва', row.get('name', '')).strip()
            if not name:
                continue
            oblast = row.get('Область', row.get('oblast', '')).strip()
            raion = row.get('Район', row.get('raion', '')).strip() or None
            lat = float(row.get('Широта', row.get('lat', 0)) or 0)
            lng = float(row.get('Довгота', row.get('lng', 0)) or 0)
            if lat == 0 or lng == 0:
                continue
            ptype = row.get('Тип', row.get('type', '')).strip() or None
            pop = int(row.get('Населення', row.get('population', 0)) or 0)

            conn.execute(
                "INSERT INTO places (name, name_lower, oblast, raion, lat, lng, place_type, population) VALUES (?,?,?,?,?,?,?,?)",
                (name, name.lower(), oblast, raion, lat, lng, ptype, pop),
            )
            count += 1

    ensure_places_fts(conn)
    conn.commit()
    conn.close()
    print(f"Imported {count} settlements from CSV into {db_path}")
    return db_path


def fetch_and_build(db_path: str = DB_PATH):
    """Download a comprehensive Ukrainian settlements CSV and build DB from it."""
    # This is a public dataset URL with koatuu/katottg or OSM localities (adjust as needed)
    csv_url = "https://raw.githubusercontent.com/Pryshchepa/ukraine-cities/master/cities.csv"
    temp_csv = "/tmp/ua_cities.csv"
    print(f"Downloading settlements data from {csv_url} ...")
    try:
        urllib.request.urlretrieve(csv_url, temp_csv)
        print("Download complete. Building DB from CSV...")
        # Note: Depending on the CSV format, build_from_csv might need mapping logic updates
        return build_from_csv(temp_csv, db_path)
    except Exception as e:
        print(f"Failed to download or build: {e}")
        print("Falling back to hardcoded data build.")
        return build_db(db_path)


